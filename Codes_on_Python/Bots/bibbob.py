async def normal_delay():
    await asyncio.sleep(
        random.uniform(
            NORMAL_MIN_DELAY,
            NORMAL_MAX_DELAY
        )
    )


async def fight_delay():
    await asyncio.sleep(
        random.uniform(
            FIGHT_MIN_DELAY,
            FIGHT_MAX_DELAY
        )
    )


# ==========================================================
# ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
# ==========================================================

def get_normal_phrases(bot_name: str):
    if bot_name == "johnny":
        return JOHNNY_NORMAL_PHRASES

    return HOMELANDER_NORMAL_PHRASES


def get_fight_phrases(bot_name: str):
    if bot_name == "johnny":
        return JOHNNY_INSULT_PHRASES

    return HOMELANDER_INSULT_PHRASES


def get_other_bot_name(bot_name: str):
    if bot_name == "johnny":
        return "homelander"

    return "johnny"


async def start_fight(
    chat_id: int,
    current_bot: Bot,
    starter_name: str,
    phrases: list[str],
):
    """Запускает новую драку и запоминает ID первой боевой реплики."""

    await fight_delay()

    phrase = random.choice(phrases)

    sent_message = await current_bot.send_message(
        chat_id,
        phrase
    )

    fight_states[chat_id] = {
        "active": True,
        "last_sender": starter_name,
        "turns": 1,
        "expected_message_id": sent_message.message_id,
    }


