def normalize_text(text: str) -> str:
    text = text.casefold().strip()

    # Убираем основные знаки препинания
    text = re.sub(r"[!?.,:;]+", "", text)

    # Несколько пробелов превращаем в один
    text = re.sub(r"\s+", " ", text)

    return text


