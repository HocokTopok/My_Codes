# ОСНОВНАЯ ОБРАБОТКА
# ==========================================================

async def process_message(
    message: Message,
    current_bot: Bot,
    bot_name: str
):
    global JOHNNY_ID, HOMELANDER_ID

    if not message.from_user:
        return

    sender_id = message.from_user.id
    chat_id = message.chat.id

    text = (message.text or "").strip()
    text_normalized = normalize_text(text)


    # ======================================================
    # 1. СООБЩЕНИЕ ЧЕЛОВЕКА
    # ======================================================

    if sender_id not in (
        JOHNNY_ID,
        HOMELANDER_ID
    ):

        # ==================================================
        # ДЖОННИ НАЗВАЛИ ЛУЧШЕ
        # -> Хоумлендер начинает драку
        # ==================================================

        if (
            text_normalized
            in JOHNNY_BETTER_TRIGGERS_NORMALIZED
        ):
            if bot_name == "homelander":
                await start_fight(
                    chat_id=chat_id,
                    current_bot=current_bot,
                    starter_name="homelander",
                    phrases=HOMELANDER_START_FIGHT_PHRASES,
                )

            return


        # ==================================================
        # ХОУМЛЕНДЕРА НАЗВАЛИ ЛУЧШЕ
        # -> Джонни начинает драку
        # ==================================================

        if (
            text_normalized
            in HOMELANDER_BETTER_TRIGGERS_NORMALIZED
        ):
            if bot_name == "johnny":
                await start_fight(
                    chat_id=chat_id,
                    current_bot=current_bot,
                    starter_name="johnny",
                    phrases=JOHNNY_START_FIGHT_PHRASES,
                )

            return


        # ==================================================
        # ОБЫЧНОЕ СООБЩЕНИЕ
        # ==================================================

        # Каждый бот независимо имеет 30% шанс ответить.
        if random.random() > REPLY_CHANCE:
            return

        await normal_delay()

        phrase = random.choice(
            get_normal_phrases(bot_name)
        )

        await current_bot.send_message(
            chat_id,
            phrase
        )

        return


    # ======================================================
    # 2. СООБЩЕНИЕ ОТ ДРУГОГО БОТА
    # ======================================================

    if bot_name == "johnny":
        other_bot_id = HOMELANDER_ID
    else:
        other_bot_id = JOHNNY_ID

    if sender_id != other_bot_id:
        return


    # ======================================================
    # 3. ПРОВЕРЯЕМ СОСТОЯНИЕ ДРАКИ
    # ======================================================

    state = fight_states.get(chat_id)

    if state is None or not state["active"]:
        return


    # ======================================================
    # 4. ЭТО ДОЛЖНА БЫТЬ ИМЕННО ПОСЛЕДНЯЯ БОЕВАЯ РЕПЛИКА
    # ======================================================

    if message.message_id != state["expected_message_id"]:
        return

    other_name = get_other_bot_name(bot_name)

    if state["last_sender"] != other_name:
        return


    # ======================================================
    # 5. ЛИМИТ ДРАКИ
    # ======================================================

    if state["turns"] >= FIGHT_MAX_TURNS:
        state["active"] = False
        return


    # ======================================================
    # 6. ОТВЕТ В ДРАКЕ
    # ======================================================

    # Запоминаем, на какую боевую реплику собираемся отвечать.
    expected_message_id = message.message_id

    await fight_delay()

    # За время ожидания пользователь мог запустить новую драку.
    # В таком случае старый ожидающий ответ больше не отправляем.
    current_state = fight_states.get(chat_id)

    if (
        current_state is not state
        or not current_state["active"]
        or current_state["expected_message_id"] != expected_message_id
    ):
        return

    phrase = random.choice(
        get_fight_phrases(bot_name)
    )

    sent_message = await current_bot.send_message(
        chat_id,
        phrase
    )

    # После успешной отправки новая боевая реплика становится
    # единственной репликой, на которую должен ответить второй бот.
    state["last_sender"] = bot_name
    state["turns"] += 1
    state["expected_message_id"] = sent_message.message_id


