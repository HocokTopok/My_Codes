void AddSeventeen(int& value)
{
  value += 17;
}

//  ------------------------------------------------------------

void Triple(int& value)
{
  value *= 3;
}

//  ------------------------------------------------------------

void ReverseDigits(int& value)
{
  int reversed = 0;

  while (value > 0)
  {
    reversed = reversed * 10 + value % 10;
    value /= 10;
  }

  value = reversed;
}

//  ------------------------------------------------------------

void AddDigitSum(int& value)
{
  int remaining = value;
  int sum = 0;

  while (remaining > 0)
  {
    sum += remaining % 10;
    remaining /= 10;
  }

  value += sum;
}

